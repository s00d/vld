//! `#[derive(Validate)]` for [vld](https://docs.rs/vld).
//!
//! Use it through `vld`'s `derive` feature (`vld::Validate`) rather than
//! depending on this crate directly. See [`macro@Validate`] for the attributes
//! and the guide at <https://s00d.github.io/vld/structs/derive>.

use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::ext::IdentExt;
use syn::spanned::Spanned;
use syn::{Data, DeriveInput, Fields, LitStr, Meta, parse_macro_input};

/// Derive macro that generates `vld_parse()`, `parse_value()`, `validate()` /
/// `is_valid()`, JSON Schema methods (with `openapi`) and implements the
/// `VldParse` trait.
///
/// # Usage
///
/// ```ignore
/// use vld::Validate;
///
/// #[derive(Debug, Validate)]
/// struct User {
///     #[vld(vld::string().min(2).max(50))]
///     name: String,
///     #[vld(vld::string().email())]
///     email: String,
///     #[vld(vld::number().int().gte(18).optional())]
///     age: Option<i64>,
/// }
///
/// let user = User::vld_parse(r#"{"name": "Alex", "email": "a@b.com"}"#).unwrap();
/// ```
///
/// The parse method is named `vld_parse` (not `parse`, as generated by
/// `vld::schema!`) so it does not shadow `clap::Parser::parse()` and similar
/// trait methods; no `parse` alias is generated for the same reason.
///
/// Field schemas of non-generic structs are built **once per process** (on
/// first use) and cached in a `static`: they must be `Send + Sync + 'static`,
/// and a schema built from runtime values freezes the values of the first
/// parse. Generic structs rebuild their schemas on every call.
///
/// # Lenient parsing
///
/// `validate_fields()` / `parse_lenient()` are generated only with the
/// struct-level `#[vld(lenient)]` attribute; they require every field type to
/// implement `Default` and `serde::Serialize`.
///
/// # Serde attributes
///
/// - struct: `rename_all = "..."` (also `rename_all(serialize = "...",
///   deserialize = "...")`), `default`
/// - field: `rename = "..."` (also `rename(serialize = "...", deserialize =
///   "...")`), `skip` / `skip_deserializing` (not validated, set to
///   `Default::default()`), `default` / `default = "path"`
/// - `flatten` and `alias` are rejected with a compile error.
///
/// `vld_parse()` / `parse_value()` / JSON Schema read the **deserialize**
/// names; `validate()` / `is_valid()` serialize the value and check it under
/// the **serialize** names, so a `Serialize`d instance validates.
///
/// With `#[serde(default)]` (field or struct) a **missing** key takes the
/// default value without running the field schema (as serde does): the
/// default is never validated. A present key is validated as usual.
///
/// ```ignore
/// #[derive(Debug, serde::Serialize, Validate)]
/// #[serde(rename_all = "camelCase")]
/// struct ApiRequest {
///     #[vld(vld::string().min(2))]
///     first_name: String,
///     #[vld(vld::string().email())]
///     email_address: String,
/// }
/// // Parses from {"firstName": "...", "emailAddress": "..."}
/// ```
///
/// Supported rename_all conventions: `lowercase`, `UPPERCASE`, `camelCase`,
/// `PascalCase`, `snake_case`, `SCREAMING_SNAKE_CASE`, `kebab-case`,
/// `SCREAMING-KEBAB-CASE`.
///
/// Raw identifiers map to their bare name (`r#type` → `"type"`).
///
/// The expression inside `#[vld(...)]` is used as-is in the generated code.
/// Make sure the types are in scope (e.g., use `vld::string()` or import via prelude).
#[proc_macro_derive(Validate, attributes(vld, into_params))]
pub fn derive_validate(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand(&input)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

struct FieldInfo {
    ident: syn::Ident,
    ty: syn::Type,
    /// Deserialize name (parsing, JSON Schema).
    key: String,
    /// Serialize name (`validate()`).
    ser_key: String,
    /// `None` = `#[serde(skip)]`: not validated, set to `Default::default()`.
    schema: Option<TokenStream2>,
    /// Value used when the key is missing (`#[serde(default)]`).
    default: Option<TokenStream2>,
}

fn expand(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let name = &input.ident;
    let (impl_generics, ty_generics, where_clause) = input.generics.split_for_impl();

    let serde_struct = parse_serde_struct_attrs(&input.attrs)?;
    let lenient = parse_vld_struct_attrs(&input.attrs)?;
    let parameter_in_expr = match get_into_params_parameter_in(&input.attrs).as_deref() {
        Some("query") => quote! { Some("query") },
        Some("path") => quote! { Some("path") },
        Some("header") => quote! { Some("header") },
        Some("cookie") => quote! { Some("cookie") },
        _ => quote! { None },
    };

    let fields = match &input.data {
        Data::Struct(data) => match &data.fields {
            Fields::Named(fields) => &fields.named,
            other => {
                return Err(syn::Error::new(
                    other.span(),
                    "Validate can only be derived for structs with named fields",
                ));
            }
        },
        _ => {
            return Err(syn::Error::new(
                name.span(),
                "Validate can only be derived for structs",
            ));
        }
    };

    let mut infos = Vec::new();
    for field in fields {
        let ident = field
            .ident
            .clone()
            .ok_or_else(|| syn::Error::new(field.span(), "expected a named field"))?;
        let serde_field = parse_serde_field_attrs(&field.attrs)?;
        let bare = ident.unraw().to_string();
        let pick = |field: Option<String>, rule: &Option<String>| match field {
            Some(k) => k,
            None => match rule {
                Some(conv) => rename_field(&bare, conv),
                None => bare.clone(),
            },
        };
        let key = pick(serde_field.rename.0, &serde_struct.rename_all.0);
        let ser_key = pick(serde_field.rename.1, &serde_struct.rename_all.1);

        let schema = if serde_field.skip {
            None
        } else {
            let attr = field
                .attrs
                .iter()
                .find(|a| a.path().is_ident("vld"))
                .ok_or_else(|| {
                    syn::Error::new(
                        ident.span(),
                        format!("field `{}` is missing a #[vld(...)] attribute", ident),
                    )
                })?;
            Some(attr.parse_args::<TokenStream2>()?)
        };

        let default = serde_field.default.or_else(|| {
            serde_struct.default.then(|| {
                let fid = &ident;
                quote! { <Self as ::std::default::Default>::default().#fid }
            })
        });

        infos.push(FieldInfo {
            ident,
            ty: field.ty.clone(),
            key,
            ser_key,
            schema,
            default,
        });
    }

    let field_idents: Vec<_> = infos.iter().map(|f| &f.ident).collect();

    // Non-generic structs build each field schema once (process-wide cache);
    // in generic code a `static` would be shared between instantiations.
    let generic = !input.generics.params.is_empty();
    let schema_ref = |schema: &TokenStream2| {
        if generic {
            quote! { &{ #schema } }
        } else {
            quote! { ::vld::__vld_cached!(#schema) }
        }
    };

    // parse_value: one `let` per field
    let parse_lets = infos.iter().map(|f| {
        let FieldInfo {
            ident,
            ty,
            key,
            ser_key,
            ..
        } = f;
        let key = if key == ser_key {
            quote! { #key }
        } else {
            quote! { if __vld_ser { #ser_key } else { #key } }
        };
        let Some(schema) = &f.schema else {
            return quote! {
                let #ident: ::std::option::Option<#ty> =
                    ::std::option::Option::Some(::std::default::Default::default());
            };
        };
        let schema_ref = schema_ref(schema);
        let parse = quote! {
            ::vld::__private::parse_field(__vld_obj, #key, #schema_ref, &mut __vld_errors)
        };
        let value = match &f.default {
            Some(d) => quote! {
                if __vld_obj.contains_key(#key) { #parse } else { ::std::option::Option::Some(#d) }
            },
            None => parse,
        };
        quote! {
            #[allow(non_snake_case)]
            let #ident: ::std::option::Option<#ty> = #value;
        }
    });

    let lenient_tokens = if lenient {
        let result_pushes = infos.iter().filter_map(|f| {
            let schema = f.schema.as_ref()?;
            let schema_ref = schema_ref(schema);
            let key = &f.key;
            let push = quote! {
                __vld_results.push(::vld::__private::field_result(__vld_obj, #key, #schema_ref));
            };
            Some(match f.default {
                Some(_) => quote! { if __vld_obj.contains_key(#key) { #push } },
                None => push,
            })
        });
        let lenient_lets = infos.iter().map(|f| {
            let FieldInfo { ident, ty, key, .. } = f;
            let Some(schema) = &f.schema else {
                return quote! { let #ident: #ty = ::std::default::Default::default(); };
            };
            let schema_ref = schema_ref(schema);
            let parse = quote! {
                ::vld::__private::lenient_field(__vld_obj, #key, #schema_ref, &mut __vld_results)
            };
            let value = match &f.default {
                Some(d) => quote! { if __vld_obj.contains_key(#key) { #parse } else { #d } },
                None => parse,
            };
            quote! {
                #[allow(non_snake_case)]
                let #ident: #ty = #value;
            }
        });
        quote! {
            /// Validate each field individually and return per-field results.
            pub fn validate_fields<__VldInputT: ::vld::schema::VldInput + ?Sized>(
                input: &__VldInputT,
            ) -> ::std::result::Result<
                ::std::vec::Vec<::vld::object::FieldResult>,
                ::vld::error::VldError,
            > {
                let __vld_json = <__VldInputT as ::vld::schema::VldInput>::to_json_value(input)?;
                Self::validate_fields_value(&__vld_json)
            }

            /// Validate each field individually from a `serde_json::Value`.
            pub fn validate_fields_value(
                __vld_json: &::vld::serde_json::Value,
            ) -> ::std::result::Result<
                ::std::vec::Vec<::vld::object::FieldResult>,
                ::vld::error::VldError,
            > {
                #[allow(unused_imports)]
                use ::vld::schema::VldSchema as _;
                let __vld_obj = ::vld::__private::expect_object(__vld_json)?;
                let mut __vld_results: ::std::vec::Vec<::vld::object::FieldResult> =
                    ::std::vec::Vec::new();
                #( #result_pushes )*
                ::std::result::Result::Ok(__vld_results)
            }

            /// Parse leniently: build the struct even when some fields fail.
            /// Invalid fields fall back to `Default::default()`.
            pub fn parse_lenient<__VldInputT: ::vld::schema::VldInput + ?Sized>(
                input: &__VldInputT,
            ) -> ::std::result::Result<::vld::object::ParseResult<Self>, ::vld::error::VldError> {
                let __vld_json = <__VldInputT as ::vld::schema::VldInput>::to_json_value(input)?;
                Self::parse_lenient_value(&__vld_json)
            }

            /// Parse leniently from a `serde_json::Value`.
            pub fn parse_lenient_value(
                __vld_json: &::vld::serde_json::Value,
            ) -> ::std::result::Result<::vld::object::ParseResult<Self>, ::vld::error::VldError> {
                #[allow(unused_imports)]
                use ::vld::schema::VldSchema as _;
                let __vld_obj = ::vld::__private::expect_object(__vld_json)?;
                let mut __vld_results: ::std::vec::Vec<::vld::object::FieldResult> =
                    ::std::vec::Vec::new();
                #( #lenient_lets )*
                ::std::result::Result::Ok(::vld::object::ParseResult::new(
                    Self { #( #field_idents, )* },
                    __vld_results,
                ))
            }
        }
    } else {
        quote! {}
    };

    let schema_entries = infos.iter().filter_map(|f| {
        let schema = f.schema.as_ref()?;
        let key = &f.key;
        let required = if f.default.is_some() {
            quote! { false }
        } else {
            quote! { __vld_field_schema.is_required() }
        };
        Some(quote! {
            {
                let __vld_field_schema = { #schema };
                (#key, __vld_field_schema.json_schema(), #required)
            }
        })
    });
    let collect_calls = infos.iter().filter_map(|f| {
        let schema = f.schema.as_ref()?;
        Some(quote! {
            ::vld::openapi::CollectNestedSchemas::collect_nested_schemas(&{ #schema }, __vld_out);
        })
    });

    let object_schema = quote! {
        ::vld::__private::object_schema(::std::vec![ #( #schema_entries ),* ])
    };
    let json_schema_body = if generic {
        object_schema
    } else {
        quote! {
            static __VLD_JSON_SCHEMA: ::vld::__private::JsonSchemaCell =
                ::vld::__private::JsonSchemaCell::new();
            __VLD_JSON_SCHEMA.get_or_init(|| #object_schema).clone()
        }
    };

    Ok(quote! {
        impl #impl_generics #name #ty_generics #where_clause {
            /// Parse and validate input data into this struct.
            ///
            /// Named `vld_parse` to avoid conflicts with other derive macros
            /// (e.g. `clap::Parser::parse()`).
            pub fn vld_parse<__VldInputT: ::vld::schema::VldInput + ?Sized>(
                input: &__VldInputT,
            ) -> ::std::result::Result<Self, ::vld::error::VldError> {
                let __vld_json = <__VldInputT as ::vld::schema::VldInput>::to_json_value(input)?;
                Self::parse_value(&__vld_json)
            }

            /// Parse and validate directly from a `serde_json::Value`.
            pub fn parse_value(
                __vld_json: &::vld::serde_json::Value,
            ) -> ::std::result::Result<Self, ::vld::error::VldError> {
                Self::__vld_parse(__vld_json, false)
            }

            /// Parse under the deserialize (`false`) or serialize (`true`) names.
            #[doc(hidden)]
            #[allow(unused_variables)]
            pub fn __vld_parse(
                __vld_json: &::vld::serde_json::Value,
                __vld_ser: bool,
            ) -> ::std::result::Result<Self, ::vld::error::VldError> {
                #[allow(unused_imports)]
                use ::vld::schema::VldSchema as _;
                let __vld_obj = ::vld::__private::expect_object(__vld_json)?;
                let mut __vld_errors = ::vld::error::VldError::new();

                #( #parse_lets )*

                // A field may fail with an issue-less error: check the values too.
                if !__vld_errors.is_empty() #( || #field_idents.is_none() )* {
                    return ::std::result::Result::Err(__vld_errors);
                }

                ::std::result::Result::Ok(Self {
                    #( #field_idents: #field_idents.unwrap(), )*
                })
            }

            #lenient_tokens
        }

        impl #impl_generics ::vld::schema::VldParse for #name #ty_generics #where_clause {
            fn vld_parse_value(
                value: &::vld::serde_json::Value,
            ) -> ::std::result::Result<Self, ::vld::error::VldError> {
                Self::parse_value(value)
            }
        }

        impl #impl_generics #name #ty_generics #where_clause {
            /// Validate an existing value that can be serialized to JSON
            /// (checked under the fields' serialize names).
            pub fn validate<__VldT: ::vld::serde::Serialize>(
                instance: &__VldT,
            ) -> ::std::result::Result<(), ::vld::error::VldError> {
                Self::__vld_parse(&::vld::__private::to_json(instance)?, true).map(|_| ())
            }

            /// Shorthand for `validate(instance).is_ok()`.
            pub fn is_valid<__VldT: ::vld::serde::Serialize>(instance: &__VldT) -> bool {
                Self::validate(instance).is_ok()
            }
        }

        ::vld::__vld_if_openapi! {
            impl #impl_generics #name #ty_generics #where_clause {
                /// Generate a JSON Schema / OpenAPI 3.1 representation of this struct.
                ///
                /// Requires the `openapi` feature on `vld`.
                pub fn json_schema() -> ::vld::serde_json::Value {
                    #[allow(unused_imports)]
                    use ::vld::schema::VldSchema as _;
                    #[allow(unused_imports)]
                    use ::vld::openapi::JsonSchema as _;
                    #json_schema_body
                }

                /// Minimal OpenAPI 3.1 document with this struct and every
                /// nested schema it references under `components.schemas`.
                ///
                /// Requires the `openapi` feature on `vld`.
                pub fn to_openapi_document() -> ::vld::serde_json::Value {
                    ::vld::__private::openapi_document(
                        stringify!(#name),
                        Self::json_schema(),
                        Self::__vld_nested_schemas(),
                    )
                }

                #[doc(hidden)]
                pub fn __vld_collect_nested_schemas(
                    __vld_out: &mut ::std::vec::Vec<::vld::openapi::NestedSchemaEntry>,
                ) {
                    #[allow(unused_imports)]
                    use ::vld::schema::VldSchema as _;
                    #( #collect_calls )*
                }

                #[doc(hidden)]
                pub fn __vld_nested_schemas()
                    -> ::std::vec::Vec<::vld::openapi::NestedSchemaEntry>
                {
                    let mut __vld_out = ::std::vec::Vec::new();
                    Self::__vld_collect_nested_schemas(&mut __vld_out);
                    __vld_out
                }
            }

            impl #impl_generics ::vld::openapi::OpenApiParameterIn for #name #ty_generics #where_clause {
                fn parameter_in() -> Option<&'static str> {
                    #parameter_in_expr
                }
            }
        }
    })
}

