/// Container-level `#[vld(lenient, dynamic)]`: `(lenient, dynamic)`.
pub(crate) fn parse_vld_struct_attrs(attrs: &[syn::Attribute]) -> syn::Result<(bool, bool)> {
    let (mut lenient, mut dynamic) = (false, false);
    for attr in attrs.iter().filter(|a| a.path().is_ident("vld")) {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("lenient") {
                lenient = true;
                Ok(())
            } else if meta.path.is_ident("dynamic") {
                dynamic = true;
                Ok(())
            } else {
                Err(meta.error("unknown vld attribute; expected `lenient` or `dynamic`"))
            }
        })?;
    }
    Ok((lenient, dynamic))
}

/// `(deserialize, serialize)` values.
pub(crate) type Names = (Option<String>, Option<String>);

#[derive(Default)]
struct SerdeStruct {
    rename_all: Names,
    default: bool,
    deny_unknown: bool,
}

#[derive(Default)]
pub(crate) struct SerdeField {
    rename: Names,
    skip: bool,
    flatten: bool,
    default: Option<TokenStream2>,
}

/// Consume the value of a serde item we do not interpret (`x`, `x = ...`, `x(...)`).
pub(crate) fn skip_meta(meta: &syn::meta::ParseNestedMeta) -> syn::Result<()> {
    if meta.input.peek(syn::Token![=]) {
        meta.value()?.parse::<syn::Expr>()?;
    } else if meta.input.peek(syn::token::Paren) {
        let _content;
        syn::parenthesized!(_content in meta.input);
    }
    Ok(())
}

/// `name = "x"` or `name(deserialize = "x", serialize = "y")` →
/// `(deserialize, serialize)` names.
pub(crate) fn names(meta: &syn::meta::ParseNestedMeta) -> syn::Result<Names> {
    if meta.input.peek(syn::Token![=]) {
        let v = meta.value()?.parse::<LitStr>()?.value();
        return Ok((Some(v.clone()), Some(v)));
    }
    let mut out: Names = (None, None);
    meta.parse_nested_meta(|inner| {
        if inner.path.is_ident("deserialize") {
            out.0 = Some(inner.value()?.parse::<LitStr>()?.value());
        } else if inner.path.is_ident("serialize") {
            out.1 = Some(inner.value()?.parse::<LitStr>()?.value());
        } else {
            skip_meta(&inner)?;
        }
        Ok(())
    })?;
    Ok(out)
}

pub(crate) fn serde_attrs(attrs: &[syn::Attribute]) -> impl Iterator<Item = &syn::Attribute> {
    attrs
        .iter()
        .filter(|a| a.path().is_ident("serde") && matches!(a.meta, Meta::List(_)))
}

fn parse_serde_struct_attrs(attrs: &[syn::Attribute]) -> syn::Result<SerdeStruct> {
    let mut out = SerdeStruct::default();
    for attr in serde_attrs(attrs) {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename_all") {
                let (de, ser) = names(&meta)?;
                for conv in de.iter().chain(ser.iter()) {
                    if !RENAME_RULES.contains(&conv.as_str()) {
                        return Err(meta.error(format!("unknown rename_all rule `{}`", conv)));
                    }
                }
                out.rename_all = (
                    de.or(out.rename_all.0.take()),
                    ser.or(out.rename_all.1.take()),
                );
            } else if meta.path.is_ident("deny_unknown_fields") {
                out.deny_unknown = true;
            } else if meta.path.is_ident("default") {
                out.default = true;
                skip_meta(&meta)?;
            } else {
                skip_meta(&meta)?;
            }
            Ok(())
        })?;
    }
    Ok(out)
}

pub(crate) fn parse_serde_field_attrs(attrs: &[syn::Attribute]) -> syn::Result<SerdeField> {
    let mut out = SerdeField::default();
    for attr in serde_attrs(attrs) {
        attr.parse_nested_meta(|meta| {
            let p = &meta.path;
            if p.is_ident("rename") {
                let (de, ser) = names(&meta)?;
                out.rename = (de.or(out.rename.0.take()), ser.or(out.rename.1.take()));
            } else if p.is_ident("skip") || p.is_ident("skip_deserializing") {
                out.skip = true;
            } else if p.is_ident("default") {
                out.default = Some(if meta.input.peek(syn::Token![=]) {
                    let path: syn::ExprPath = meta.value()?.parse::<LitStr>()?.parse()?;
                    quote! { #path() }
                } else {
                    quote! { ::std::default::Default::default() }
                });
            } else if p.is_ident("flatten") {
                out.flatten = true;
            } else if p.is_ident("alias") {
                return Err(meta.error(format!(
                    "vld: #[serde({})] is not supported by #[derive(Validate)]",
                    p.get_ident().map(|i| i.to_string()).unwrap_or_default()
                )));
            } else {
                skip_meta(&meta)?;
            }
            Ok(())
        })?;
    }
    Ok(out)
}

/// Extract `#[into_params(parameter_in = ...)]` from struct-level attributes.
fn get_into_params_parameter_in(attrs: &[syn::Attribute]) -> Option<String> {
    let mut found = None;
    for attr in attrs.iter().filter(|a| a.path().is_ident("into_params")) {
        let _ = attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("parameter_in") {
                let expr: syn::Expr = meta.value()?.parse()?;
                if let syn::Expr::Path(path) = expr {
                    if let Some(ident) = path.path.get_ident() {
                        found = Some(ident.to_string().to_ascii_lowercase());
                    }
                }
            } else {
                skip_meta(&meta)?;
            }
            Ok(())
        });
        if found.is_some() {
            break;
        }
    }
    found
}

pub(crate) const RENAME_RULES: &[&str] = &[
    "lowercase",
    "UPPERCASE",
    "PascalCase",
    "camelCase",
    "snake_case",
    "SCREAMING_SNAKE_CASE",
    "kebab-case",
    "SCREAMING-KEBAB-CASE",
];

/// Convert a snake_case field name to the given serde naming convention.
pub(crate) fn rename_field(name: &str, convention: &str) -> String {
    match convention {
        "lowercase" => name.to_ascii_lowercase(),
        "UPPERCASE" => name.to_ascii_uppercase(),
        "camelCase" => {
            let pascal = to_pascal_case(name);
            let mut chars = pascal.chars();
            match chars.next() {
                Some(first) => first.to_lowercase().chain(chars).collect(),
                None => pascal,
            }
        }
        "PascalCase" => to_pascal_case(name),
        "SCREAMING_SNAKE_CASE" => name.to_ascii_uppercase(),
        "kebab-case" => name.replace('_', "-"),
        "SCREAMING-KEBAB-CASE" => name.replace('_', "-").to_ascii_uppercase(),
        _ => name.to_string(),
    }
}

pub(crate) fn to_pascal_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize_next = true;
    for ch in s.chars() {
        if ch == '_' {
            capitalize_next = true;
        } else if capitalize_next {
            result.extend(ch.to_uppercase());
            capitalize_next = false;
        } else {
            result.push(ch);
        }
    }
    result
}

#[cfg(test)]
mod tests {
    use super::rename_field;

    #[test]
    fn rename_rules() {
        assert_eq!(rename_field("first_name", "camelCase"), "firstName");
        assert_eq!(rename_field("first_name", "PascalCase"), "FirstName");
        assert_eq!(rename_field("first_name", "lowercase"), "first_name");
        assert_eq!(rename_field("first_name", "UPPERCASE"), "FIRST_NAME");
        assert_eq!(rename_field("first_name", "kebab-case"), "first-name");
        assert_eq!(
            rename_field("first_name", "SCREAMING-KEBAB-CASE"),
            "FIRST-NAME"
        );
    }
}
